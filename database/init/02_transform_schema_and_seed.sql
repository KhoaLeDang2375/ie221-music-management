BEGIN;

-- 1. Enable pgcrypto for bcrypt password hashing (compatible with Python bcrypt)
CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- =============================================================================
-- 2. CREATE TABLE app_user & SEED RULE-BASED USERS FROM CHINOOK
-- =============================================================================
CREATE TABLE app_user (
    user_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL,
    email VARCHAR(255) NOT NULL,
    full_name VARCHAR(120) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL DEFAULT 'user',
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT app_user_username_key UNIQUE (username),
    CONSTRAINT app_user_email_key UNIQUE (email),
    CONSTRAINT app_user_role_check CHECK (role IN ('user', 'admin'))
);

-- 2.1. Insert fixed default accounts for testing (admin@123, testuser@123)
INSERT INTO app_user (username, email, full_name, password_hash, role, is_active, created_at)
VALUES
    ('admin', 'admin@music.local', 'System Administrator', crypt('admin@123', gen_salt('bf', 10)), 'admin', TRUE, CURRENT_TIMESTAMP - INTERVAL '90 days'),
    ('testuser', 'testuser@music.local', 'Test Registered User', crypt('testuser@123', gen_salt('bf', 10)), 'user', TRUE, CURRENT_TIMESTAMP - INTERVAL '60 days');

-- 2.2. Migrate Chinook Employees (employee_id 1, 2 -> admin; 3..8 -> user)
-- Rule-based username: email prefix (lowercased, ASCII normalized)
-- Rule-based password: <username>@123 (guaranteed >= 8 chars per BR-09)
INSERT INTO app_user (username, email, full_name, password_hash, role, is_active, created_at)
SELECT
    u.uname AS username,
    e.email,
    e.first_name || ' ' || e.last_name AS full_name,
    crypt(u.uname || '@123', gen_salt('bf', 10)) AS password_hash,
    CASE WHEN e.employee_id IN (1, 2) THEN 'admin' ELSE 'user' END AS role,
    TRUE AS is_active,
    CURRENT_TIMESTAMP - (INTERVAL '1 day' * (80 - e.employee_id)) AS created_at
FROM employee e
CROSS JOIN LATERAL (
    SELECT translate(split_part(lower(e.email), '@', 1), 'łó', 'lo') AS uname
) u
ORDER BY e.employee_id;

-- 2.3. Migrate Chinook Customers (59 customers -> role = 'user')
-- Rule-based username: email prefix (lowercased, ASCII normalized)
-- Rule-based password: <username>@123
-- Set customer_id 58, 59 to is_active = FALSE to test locked account behavior (BR-06, UC-02)
INSERT INTO app_user (username, email, full_name, password_hash, role, is_active, created_at)
SELECT
    u.uname AS username,
    c.email,
    c.first_name || ' ' || c.last_name AS full_name,
    crypt(u.uname || '@123', gen_salt('bf', 10)) AS password_hash,
    'user' AS role,
    CASE WHEN c.customer_id IN (58, 59) THEN FALSE ELSE TRUE END AS is_active,
    CURRENT_TIMESTAMP - (INTERVAL '1 day' * (65 - c.customer_id)) AS created_at
FROM customer c
CROSS JOIN LATERAL (
    SELECT translate(split_part(lower(c.email), '@', 1), 'łó', 'lo') AS uname
) u
ORDER BY c.customer_id;

-- =============================================================================
-- 3. DROP OUT-OF-SCOPE SALES & HR TABLES (Section 9 of Requirements)
-- =============================================================================
DROP TABLE invoice_line;
DROP TABLE invoice;
DROP TABLE customer;
DROP TABLE employee;

-- =============================================================================
-- 4. ADJUST CATALOG TABLES (artist, album, genre, media_type, track)
-- =============================================================================

-- 4.1. artist: NOT NULL & UNIQUE on name (UC-15, FR-09), Identity PK
ALTER TABLE artist
    ALTER COLUMN artist_id ADD GENERATED BY DEFAULT AS IDENTITY,
    ALTER COLUMN name SET NOT NULL,
    ADD CONSTRAINT artist_name_key UNIQUE (name);

-- 4.2. album: ON DELETE RESTRICT for artist_id (BR-04), Identity PK
ALTER TABLE album
    ALTER COLUMN album_id ADD GENERATED BY DEFAULT AS IDENTITY,
    DROP CONSTRAINT album_artist_id_fkey,
    ADD CONSTRAINT album_artist_id_fkey
        FOREIGN KEY (artist_id) REFERENCES artist (artist_id)
        ON DELETE RESTRICT ON UPDATE CASCADE;

-- 4.3. genre: NOT NULL & UNIQUE on name (UC-15, FR-09), Identity PK
ALTER TABLE genre
    ALTER COLUMN genre_id ADD GENERATED BY DEFAULT AS IDENTITY,
    ALTER COLUMN name SET NOT NULL,
    ADD CONSTRAINT genre_name_key UNIQUE (name);

-- 4.4. media_type: NOT NULL & UNIQUE on name, Identity PK
ALTER TABLE media_type
    ALTER COLUMN media_type_id ADD GENERATED BY DEFAULT AS IDENTITY,
    ALTER COLUMN name SET NOT NULL,
    ADD CONSTRAINT media_type_name_key UNIQUE (name);

-- 4.5. track:
--   - Rename milliseconds -> duration_ms
--   - Drop out-of-scope columns: bytes, unit_price (Section 6 & Section 9)
--   - Add CHECK (duration_ms > 0) (UC-14)
--   - Set FK ON DELETE RESTRICT (BR-04)
ALTER TABLE track RENAME COLUMN milliseconds TO duration_ms;

ALTER TABLE track
    ALTER COLUMN track_id ADD GENERATED BY DEFAULT AS IDENTITY,
    DROP COLUMN bytes,
    DROP COLUMN unit_price,
    ADD CONSTRAINT track_duration_ms_check CHECK (duration_ms > 0),
    DROP CONSTRAINT track_album_id_fkey,
    ADD CONSTRAINT track_album_id_fkey
        FOREIGN KEY (album_id) REFERENCES album (album_id)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    DROP CONSTRAINT track_genre_id_fkey,
    ADD CONSTRAINT track_genre_id_fkey
        FOREIGN KEY (genre_id) REFERENCES genre (genre_id)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    DROP CONSTRAINT track_media_type_id_fkey,
    ADD CONSTRAINT track_media_type_id_fkey
        FOREIGN KEY (media_type_id) REFERENCES media_type (media_type_id)
        ON DELETE RESTRICT ON UPDATE CASCADE;

-- =============================================================================
-- 5. ADJUST PLAYLIST & PLAYLIST_TRACK TABLES (UC-06..UC-11, BR-02..BR-05)
-- =============================================================================

-- 5.1. playlist: add description, user_id, created_at
ALTER TABLE playlist
    ALTER COLUMN playlist_id ADD GENERATED BY DEFAULT AS IDENTITY,
    ALTER COLUMN name TYPE VARCHAR(100),
    ALTER COLUMN name SET NOT NULL,
    ADD COLUMN description TEXT,
    ADD COLUMN user_id INT,
    ADD COLUMN created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP;

-- Assign existing 18 Chinook playlists across sample users (user_id 1..10)
-- so each user's playlist names are unique per (user_id, name) (BR-05)
UPDATE playlist
SET
    user_id = ((playlist_id - 1) % 10) + 1,
    description = 'Curated collection: ' || name,
    created_at = CURRENT_TIMESTAMP - (INTERVAL '2 days' * (20 - playlist_id));

ALTER TABLE playlist
    ALTER COLUMN user_id SET NOT NULL,
    ADD CONSTRAINT playlist_user_id_fkey
        FOREIGN KEY (user_id) REFERENCES app_user (user_id)
        ON DELETE CASCADE ON UPDATE CASCADE,
    ADD CONSTRAINT playlist_name_length_check
        CHECK (char_length(trim(name)) BETWEEN 1 AND 100),
    ADD CONSTRAINT playlist_user_id_name_key
        UNIQUE (user_id, name);

CREATE INDEX playlist_user_id_idx ON playlist (user_id);

-- 5.2. playlist_track: add added_at (UC-10), ON DELETE CASCADE on both FKs (BR-04, UC-09)
ALTER TABLE playlist_track
    ADD COLUMN added_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    DROP CONSTRAINT playlist_track_playlist_id_fkey,
    ADD CONSTRAINT playlist_track_playlist_id_fkey
        FOREIGN KEY (playlist_id) REFERENCES playlist (playlist_id)
        ON DELETE CASCADE ON UPDATE CASCADE,
    DROP CONSTRAINT playlist_track_track_id_fkey,
    ADD CONSTRAINT playlist_track_track_id_fkey
        FOREIGN KEY (track_id) REFERENCES track (track_id)
        ON DELETE CASCADE ON UPDATE CASCADE;

-- =============================================================================
-- 6. CREATE 9th TABLE: listening_history (UC-13, FR-17 [Could]) + MOCK DATA
-- =============================================================================
CREATE TABLE listening_history (
    history_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INT NOT NULL,
    track_id INT NOT NULL,
    listened_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT listening_history_user_id_fkey
        FOREIGN KEY (user_id) REFERENCES app_user (user_id)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT listening_history_track_id_fkey
        FOREIGN KEY (track_id) REFERENCES track (track_id)
        ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE INDEX listening_history_user_time_idx
    ON listening_history (user_id, listened_at DESC);

-- Seed 300 realistic listening history records across active users
-- Includes >25 plays for user_id = 2 (testuser) and repeated plays of favorite tracks
INSERT INTO listening_history (user_id, track_id, listened_at)
SELECT
    CASE
        WHEN gs <= 30 THEN 2                              -- 30 plays for testuser (to test top-20 limit in UC-13)
        WHEN gs <= 55 THEN 1                              -- 25 plays for admin
        ELSE ((gs - 1) % 25) + 3                          -- distributed across users 3..27
    END AS user_id,
    ((gs * 37) % 3503) + 1 AS track_id,                   -- deterministic spread across 3,503 Chinook tracks
    CURRENT_TIMESTAMP - (INTERVAL '15 minutes' * (305 - gs)) AS listened_at
FROM generate_series(1, 300) AS gs;

-- Add explicit repeated listens of the same track by testuser (user_id = 2)
-- to demonstrate "Một người có thể nghe một bài nhiều lần" (Domain Model Section 6)
INSERT INTO listening_history (user_id, track_id, listened_at)
VALUES
    (2, 1, CURRENT_TIMESTAMP - INTERVAL '3 hours'),
    (2, 1, CURRENT_TIMESTAMP - INTERVAL '2 hours'),
    (2, 1, CURRENT_TIMESTAMP - INTERVAL '30 minutes');

-- =============================================================================
-- 7. SYNCHRONIZE ALL IDENTITY SEQUENCES
-- =============================================================================
SELECT setval(pg_get_serial_sequence('app_user', 'user_id'), COALESCE((SELECT MAX(user_id) FROM app_user), 1));
SELECT setval(pg_get_serial_sequence('artist', 'artist_id'), COALESCE((SELECT MAX(artist_id) FROM artist), 1));
SELECT setval(pg_get_serial_sequence('album', 'album_id'), COALESCE((SELECT MAX(album_id) FROM album), 1));
SELECT setval(pg_get_serial_sequence('genre', 'genre_id'), COALESCE((SELECT MAX(genre_id) FROM genre), 1));
SELECT setval(pg_get_serial_sequence('media_type', 'media_type_id'), COALESCE((SELECT MAX(media_type_id) FROM media_type), 1));
SELECT setval(pg_get_serial_sequence('track', 'track_id'), COALESCE((SELECT MAX(track_id) FROM track), 1));
SELECT setval(pg_get_serial_sequence('playlist', 'playlist_id'), COALESCE((SELECT MAX(playlist_id) FROM playlist), 1));
SELECT setval(pg_get_serial_sequence('listening_history', 'history_id'), COALESCE((SELECT MAX(history_id) FROM listening_history), 1));

COMMIT;
